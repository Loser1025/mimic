requests = []

for i, slide in enumerate(slides):
    slide_id = slide["objectId"]
    notes_content = speaker_notes.get(slide_id, "")

    if not notes_content:
        print(f"Slide {i+1} ({slide_id}): no notes defined, skipping")
        continue

    notes_page = slide.get("slideProperties", {}).get("notesPage", {})

    # ノートの本文テキストボックスを見つける（BODY placeholder）
    notes_element_id = None
    for el in notes_page.get("pageElements", []):
        shape = el.get("shape", {})
        placeholder = shape.get("placeholder", {})
        if placeholder.get("type") == "BODY":
            notes_element_id = el["objectId"]
            break

    if not notes_element_id:
        print(f"Slide {i+1} ({slide_id}): BODY placeholder not found")
        continue

    print(f"Slide {i+1} ({slide_id}): updating notes (element: {notes_element_id})")

    # 既存テキストがある場合のみ削除
    has_existing_text = False
    for el in notes_page.get("pageElements", []):
        if el["objectId"] == notes_element_id:
            text_obj = el.get("shape", {}).get("text", {})
            existing = "".join(
                te.get("textRun", {}).get("content", "")
                for te in text_obj.get("textElements", [])
            )
            if existing.strip():
                has_existing_text = True
            break

    if has_existing_text:
        requests.append({
            "deleteText": {
                "objectId": notes_element_id,
                "textRange": {"type": "ALL"}
            }
        })

    # 新しいテキストを挿入
    requests.append({
        "insertText": {
            "objectId": notes_element_id,
            "insertionIndex": 0,
            "text": notes_content
        }
    })

# バッチ更新を実行
if requests:
    print(f"\nSending {len(requests)} requests...")
    response = service.presentations().batchUpdate(
        presentationId=PRESENTATION_ID,
        body={"requests": requests}
    ).execute()
    print("Done! Speaker notes updated successfully.")
else:
    print("No requests to send.")
