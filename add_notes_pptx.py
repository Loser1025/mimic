def get_current_notes_text(slide):
    """スライドの現在のノートテキストを取得"""
    notes_slide = slide.has_notes_slide and slide.notes_slide or None
    if notes_slide is None:
        return ""
    tf = notes_slide.notes_text_frame
    return tf.text.strip() if tf else ""


def add_notes_to_slide(slide, new_text):
    """スライドのノートに追記する"""
    notes_slide = slide.notes_slide
    tf = notes_slide.notes_text_frame

    existing = tf.text.strip()

    if existing:
        separator = "\n\n---【文字起こし追記】---\n"
        full_text = existing + separator + new_text
    else:
        full_text = new_text

    # 全テキストをクリアして再設定
    tf.clear()
    p = tf.paragraphs[0]
    p.text = full_text


def main():
    print(f"入力: {INPUT_PATH}")
    prs = Presentation(INPUT_PATH)

    print(f"スライド数: {len(prs.slides)}")

    for idx, slide in enumerate(prs.slides):
        if idx not in SPEAKER_NOTES:
            print(f"  スライド{idx+1}: スキップ（ノート定義なし）")
            continue

        current = get_current_notes_text(slide)
        add_notes_to_slide(slide, SPEAKER_NOTES[idx])
        status = "（既存あり→追記）" if current else "（新規追加）"
        print(f"  スライド{idx+1}: ノート追記完了 {status}")

    prs.save(OUTPUT_PATH)
    print(f"\n保存完了: {OUTPUT_PATH}")


if __name__ == "__main__":
    main()
