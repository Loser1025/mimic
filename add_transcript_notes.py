def get_current_notes_text(slide):
    if not slide.has_notes_slide:
        return ""
    return slide.notes_slide.notes_text_frame.text.strip()


def set_notes_text(slide, text):
    notes_slide = slide.notes_slide
    tf = notes_slide.notes_text_frame
    tf.clear()
    tf.paragraphs[0].text = text


def main():
    print(f"読み込み: {INPUT_PATH}")
    prs = Presentation(INPUT_PATH)
    print(f"スライド数: {len(prs.slides)}")

    for idx, slide in enumerate(prs.slides):
        if idx not in ADDON:
            print(f"  スライド{idx+1}: スキップ（追記定義なし）")
            continue

        existing = get_current_notes_text(slide)
        new_content = ADDON[idx]

        # スライド30(インデックス29)は区切り線をADDON側で制御済み
        if idx == 29:
            full_text = existing + new_content
        else:
            full_text = existing + SEP + new_content

        set_notes_text(slide, full_text)
        print(f"  スライド{idx+1}: 追記完了")

    prs.save(OUTPUT_PATH)
    print(f"\n保存完了: {OUTPUT_PATH}")


if __name__ == "__main__":
    main()
