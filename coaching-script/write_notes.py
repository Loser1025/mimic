# ===== API 処理 =====
creds = service_account.Credentials.from_service_account_file(SA_KEY_PATH, scopes=SCOPES)
service = build("slides", "v1", credentials=creds)

presentation = service.presentations().get(presentationId=PRESENTATION_ID).execute()
slides = presentation.get("slides", [])

requests = []

for slide in slides:
    slide_id = slide.get("objectId", "")
    if slide_id not in NOTES:
        continue

    notes_page = slide.get("slideProperties", {}).get("notesPage", {})
    notes_body_id = None
    current_text_len = 0

    for el in notes_page.get("pageElements", []):
        shape = el.get("shape", {})
        ph = shape.get("placeholder", {})
        if ph.get("type") == "BODY":
            notes_body_id = el.get("objectId", "")
            for te in shape.get("text", {}).get("textElements", []):
                current_text_len += len(te.get("textRun", {}).get("content", ""))
            break

    if not notes_body_id:
        print(f"[SKIP] {slide_id} - notes body not found")
        continue

    # 既存テキストを削除してから新規挿入
    if current_text_len > 0:
        requests.append({
            "deleteText": {
                "objectId": notes_body_id,
                "textRange": {"type": "ALL"}
            }
        })

    requests.append({
        "insertText": {
            "objectId": notes_body_id,
            "insertionIndex": 0,
            "text": NOTES[slide_id]
        }
    })

    print(f"[OK] {slide_id} - {len(NOTES[slide_id])}文字 書き込み予定")

print(f"\n合計 {len(requests)} リクエストを送信します...")

result = service.presentations().batchUpdate(
    presentationId=PRESENTATION_ID,
    body={"requests": requests}
).execute()

print("完了！")
